"""Exports the Python content library and scoring tables to js/data.js so the browser engine uses
exactly the same text and numbers as the Python engine.   python tools/build_js_data.py"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from content import extra, misc, numbers, signs, traits, vedic  # noqa: E402
from engine import astro, compat, places, synthesis as S  # noqa: E402


def pair(d):
    return {"|".join(k): v for k, v in d.items()}


D = {
    "SIGN_TEXT": signs.SIGN_TEXT, "TRAITS": traits.TRAITS, "TENSIONS": pair(traits.TENSIONS),
    "NUMBERS": numbers.NUMBERS, "KARMIC_DEBT": numbers.KARMIC_DEBT, "CATEGORY_INTRO": numbers.CATEGORY_INTRO,
    "NAKSHATRA_INFO": vedic.NAKSHATRA_INFO, "MAHA_TEXT": vedic.MAHA_TEXT, "ANTAR_FLAVOR": vedic.ANTAR_FLAVOR,
    "SADE_SATI": vedic.SADE_SATI, "YOGAS": vedic.YOGAS,
    "PAIR_ASPECTS": pair(misc.PAIR_ASPECTS), "ELEMENT_TEXT": misc.ELEMENT_TEXT, "MODALITY_TEXT": misc.MODALITY_TEXT,
    "DISCLAIMER": misc.DISCLAIMER, "DIMENSION_TEXT": misc.DIMENSION_TEXT, "DIMENSION_TITLE": misc.DIMENSION_TITLE,
    "RELATION_TIPS": misc.RELATION_TIPS, "RELATION_TYPES": misc.RELATION_TYPES,
    "EXTRA": {k: getattr(extra, k) for k in ["STEMS", "BRANCHES", "ANIMALS", "STEM_ELEMENT", "BRANCH_ELEMENT", "DAY_MASTER",
              "ANIMAL_TEXT", "ELEMENT_BALANCE", "HOUSE_NAME", "HOUSE_THEME", "PLANET_HOUSE_LEAD", "JUPITER_SIGN",
              "SATURN_SIGN", "YEAR_LORD"]},
    "BAZI_REL": {"SIX_HARMONY": [sorted(x) for x in extra.SIX_HARMONY], "TRINES": [sorted(x) for x in extra.TRINES],
                 "CLASHES": [sorted(x) for x in extra.CLASHES]},
    "SYN": {"SIGN_VEC": S.SIGN_VEC, "NUM_VEC": S.NUM_VEC, "DM_VEC": S.DM_VEC, "ANIMAL_VEC": S.ANIMAL_VEC,
            "ELEMENT_VEC": S.ELEMENT_VEC, "W_WEIGHTS": S.W_WEIGHTS, "V_WEIGHTS": S.V_WEIGHTS, "N_WEIGHTS": S.N_WEIGHTS,
            "B_WEIGHTS": S.B_WEIGHTS, "DOMAINS": S.DOMAINS, "SYSTEMS": S.SYSTEMS, "SYSTEM_WEIGHT": S.SYSTEM_WEIGHT,
            "PRIOR": S.PRIOR, "SUPPORT": S.SUPPORT, "BASELINE": S.BASELINE, "TRAIT_KEYS": S.TRAIT_KEYS},
    "COMPAT": {"DIMENSIONS": compat.DIMENSIONS, "WEIGHTS": compat.WEIGHTS, "METHOD_WEIGHTS": compat.METHOD_WEIGHTS,
               "ANIMAL_SCORE": compat.ANIMAL_SCORE, "ANIMAL_NOTE": compat.ANIMAL_NOTE, "ELEMENT_SCORE": compat.ELEMENT_SCORE,
               "ELEMENT_NOTE": compat.ELEMENT_NOTE, "YONI_M": compat.YONI_M, "YONI_ORDER": compat.YONI_ORDER,
               "GANA_SCORE": pair(compat.GANA_SCORE), "FRIENDS": {k: [sorted(v[0]), sorted(v[1])] for k, v in compat.FRIENDS.items()},
               "VARNA_RANK": compat.VARNA_RANK, "VASHYA": compat.VASHYA, "VAL": compat.VAL},
    "ASTRO": {"NAKSHATRAS": astro.NAKSHATRAS, "DASHA_ORDER": astro.DASHA_ORDER, "DASHA_YEARS": astro.DASHA_YEARS,
              "DOMICILE": astro.DOMICILE, "EXALT": astro.EXALT},
    "PLACES": places.PLACES,
}
out = ROOT / "js" / "data.js"
out.write_text("/* Generated by tools/build_js_data.py. Do not edit. */\nglobalThis.ABDATA = "
               + json.dumps(D, ensure_ascii=False, separators=(",", ":")) + ";\n")
print("wrote", out, out.stat().st_size // 1024, "KB")
