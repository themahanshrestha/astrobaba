def level_label(r):
    n = len(r["supporters"])
    names = ", ".join(SYS_NAME[x] for x in r["supporters"])
    if n >= 3:
        return f"Strong theme · {n} of 4 systems agree ({names})"
    if n == 2:
        return f"Supported · {names} agree"
    if n == 1:
        return f"Emphasised by {names}"
    return ""


def _opts(dist: dict[str, float], min_p: float = 0.2) -> list[tuple[str, float]]:
    items = [(k, v) for k, v in dist.items() if v >= min_p]
    return items or list(dist.items())[:1]


def _block(h, text=None, items=None, src=None, time=False, kind="text"):
    b = {"h": h, "src": src or [], "time": time, "kind": kind}
    if text is not None:
        b["text"] = text
    if items is not None:
        b["items"] = items
    return b


def _sign_view(h, field, w_dist, v_dist, w_label, v_label, time=False):
    """Western vs Vedic reading of the same body, merged when both agree."""
    ws, vs = _opts(w_dist), _opts(v_dist)
    if len(ws) == 1 and len(vs) == 1 and ws[0][0] == vs[0][0]:
        s = ws[0][0]
        return _block(h, text=SIGN_TEXT[s][field], time=time,
                      src=[f"{w_label} in {s} · Western", f"{v_label} in {s} · Vedic",
                           "Both traditions agree on this placement"])
    items = []
    for s, p in ws:
        items.append({"label": f"Western · {s}" + (f" ({int(p*100)}% likely)" if p < .95 else ""),
                      "text": SIGN_TEXT[s][field]})
    for s, p in vs:
        items.append({"label": f"Vedic · {s}" + (f" ({int(p*100)}% likely)" if p < .95 else ""),
                      "text": SIGN_TEXT[s][field]})
    return _block(h, items=items, kind="views", time=time,
                  src=[f"{w_label} · Western (tropical)", f"{v_label} · Vedic (sidereal, Lahiri)"])


def _planet_dists(prof, planet):
    wd = prof["dist"]["w"].get(planet.lower()) or {prof["western"]["planets"][planet]["sign"]: 1.0}
    vd = prof["dist"]["v"].get(planet.lower()) or {prof["vedic"]["planets"][planet]["sign"]: 1.0}
    return wd, vd


def _lead(rows, k=3):
    return [r for r in rows[:k]]


def _trait_chip(r):
    t = TRAITS[r["trait"]]
    return {"key": r["trait"], "name": t["title"], "tag": t["tag"], "level": r["level"],
            "level_label": level_label(r), "score": r["score"], "per_system": r["per_system"]}


def _trait_block(r, field, heading=None):
    t = TRAITS[r["trait"]]
    return _block(heading or t["title"], text=t[field],
                  src=[e["source"] for e in r["evidence"]], time=any(e["needs_time"] for e in r["evidence"]))


def meta_exact(prof):
    return prof["meta"]["time_mode"] == "exact"


def _asp(prof, a, b):
    for x in prof["western"]["aspects"]:
        if {x["a"], x["b"]} == {a, b}:
            return x
    return None


